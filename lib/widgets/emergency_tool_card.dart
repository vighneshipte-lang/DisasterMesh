
import 'package:flutter/material.dart';
import '../theme/app_theme.dart';

class EmergencyToolCard extends StatelessWidget {
  final String title;
  final String subtitle;
  final IconData icon;
  final Color iconColor;
  final VoidCallback onTap;

  const EmergencyToolCard({
